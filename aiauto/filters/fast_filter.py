# ============================================================
# Основная функция
# ============================================================

def classify_fast(
    title: str,
    snippet: str = "",
    it_protect_markers: tuple[str, ...] | list[str] | None = None,
    hard_reject_markers: tuple[str, ...] | list[str] | None = None,
) -> dict:
    """
    Быстрая классификация карточки HH. Whitelist-first.

    Возвращает:

        {
            "status": "HARD_REJECT" | "TARGET" | "REVIEW_BY_AI",
            "reason": str,
        }

    Порядок:

        1. Пустые данные -> REVIEW_BY_AI (буквально нет данных
           для решения — крайне редкий случай).
        2. Явная IT-профессия по whitelist (title) -> TARGET.
        3. Устойчивая IT-комбинация (level 2, title) -> TARGET.
        4. Принудительный не-IT список (title) -> HARD_REJECT.
        5. Всё остальное -> HARD_REJECT (whitelist не подтвердил
           IT — по умолчанию отбрасываем, а не отправляем в Qwen).

    it_protect_markers / hard_reject_markers параметры сохранены
    для обратной совместимости с текущим вызовом из hh/search.py
    (config.py передаёт их явно). Если переданы — используются
    вместо DEFAULT_*.
    """

    it_markers = (
        tuple(it_protect_markers)
        if it_protect_markers is not None
        else DEFAULT_IT_PROTECT_MARKERS
    )

    force_reject_markers = (
        tuple(hard_reject_markers)
        if hard_reject_markers is not None
        else DEFAULT_FORCE_HARD_REJECT_MARKERS
    )

    title_normalized = _normalize(title)
    snippet_normalized = _normalize(snippet)

    if not title_normalized and not snippet_normalized:
        return {
            "status": "REVIEW_BY_AI",
            "reason": (
                "ambiguous — нет данных (пустые title и snippet), "
                "передано в основной pipeline"
            ),
        }

    # 1. Middle/Senior/Lead — абсолютный REJECT.
    seniority_match = _TITLE_SENIORITY_RE.search(title_normalized)
    if seniority_match:
        return {
            "status": "HARD_REJECT",
            "reason": (
                "seniority_title: в названии обнаружен запрещённый "
                f"уровень '{seniority_match.group(0).strip()}'"
            ),
        }

    # 2. Отдельно разрешённые пользователем целевые профессии:
    # Performance Marketing / SEO(+Technical SEO) / Data-BI.
    # Они проверяются ДО общего blacklist, потому что в старом
    # blacklist есть слово "маркетолог", а Technical SEO может
    # пересечься с ранними нетаргетными техническими маркерами.
    extended_role = detect_extended_target_role(title_normalized)
    if extended_role is not None:
        extended_block = _text_has_any(
            title_normalized,
            EXTENDED_TARGET_TITLE_HARD_REJECT_MARKERS,
        )
        if extended_block is not None:
            return {
                "status": "HARD_REJECT",
                "reason": (
                    "extended_target_conflict: целевая профессия "
                    f"'{extended_role}', но в названии есть запрещённая "
                    f"клиентская/продажная роль '{extended_block}'"
                ),
            }

        return {
            "status": "TARGET",
            "reason": (
                "extended_target_whitelist: разрешённое направление "
                f"'{extended_role}'"
            ),
        }

    # 3. Blacklist имеет приоритет над обычным IT-whitelist.
    force_reject_hit = _text_has_any(
        title_normalized,
        force_reject_markers,
    )
    if force_reject_hit is not None:
        return {
            "status": "HARD_REJECT",
            "reason": f"force_non_it_title: '{force_reject_hit}'",
        }

    # 4. Явный IT whitelist.
    it_hit = _text_has_any(title_normalized, it_markers)
    if it_hit is not None:
        return {
            "status": "TARGET",
            "reason": f"whitelist: явный IT-маркер в названии: '{it_hit}'",
        }

    # 5. Устойчивые IT-комбинации.
    for word_a, word_b in LEVEL2_COMBINATIONS:
        if _text_has_all(title_normalized, (word_a, word_b)):
            return {
                "status": "TARGET",
                "reason": (
                    "whitelist: устойчивая IT-комбинация в "
                    f"названии: '{word_a}' + '{word_b}'"
                ),
            }

    # 6. Всё остальное — REJECT.
    return {
        "status": "HARD_REJECT",
        "reason": (
            "not_in_whitelist — название не подтверждено "
            "IT-whitelist, отброшено без обращения к Qwen"
        ),
    }