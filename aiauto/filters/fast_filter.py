# Нормализация
# ============================================================

def _normalize(text: str) -> str:
    """
    Нормализация текста для устойчивого substring-поиска.
    """
    return " ".join(
        str(text or "")
        .lower()
        .replace("ё", "е")
        .replace("\xa0", " ")
        .split()
    ).strip()


def _is_word_char(ch: str) -> bool:
    """
    Буква или цифра (латиница/кириллица) — то, что считаем частью
    "слова" для проверки границы совпадения. isalnum() у Python
    юникод-aware и корректно работает с кириллицей.
    """
    return bool(ch) and ch.isalnum()


def _marker_matches(haystack: str, marker: str) -> bool:
    """
    ИСПРАВЛЕНИЕ (реальный прогон, ложный HARD_REJECT):
    Раньше здесь была голая проверка `marker in haystack`, которая
    ловила маркер как ЛЮБУЮ подстроку, включая случайное вклинивание
    в середину постороннего слова. Подтверждённые на реальных
    прогонах случаи:

        - "QA Automation Engineer (производительность и нагрузочное
          тестирование)" — принудительный blacklist-маркер
          "водитель" совпал как подстрока внутри слова
          "произВОДИТЕЛЬность", и явная QA-вакансия была отброшена
          HARD_REJECT ещё до обращения к Qwen.

    Проверяется ЛЕВАЯ граница совпадения: символ непосредственно
    перед началом marker не должен быть буквой/цифрой. Этого
    достаточно, чтобы исключить вклинивание в середину слова (как
    в примере выше), и одновременно НЕ ломает поиск с учётом русских
    падежных окончаний: маркер "тестировщик" по-прежнему находит
    "тестировщика", "тестировщику", "тестировщиков" и т.п., потому
    что там нарушения именно ЛЕВОЙ границы нет (падежное окончание
    добавляется СПРАВА и никогда не создаёт ложных совпадений с
    другим словом, в отличие от левой границы).

    Правая граница намеренно НЕ проверяется по этой же причине —
    строгая проверка \\b с обеих сторон (regex) отсекла бы валидные
    словоформы и уменьшила бы recall whitelist/blacklist без
    реальной пользы.
    """
    start = 0
    while True:
        idx = haystack.find(marker, start)
        if idx == -1:
            return False

        before = haystack[idx - 1] if idx > 0 else ""
        if not _is_word_char(before):
            return True

        start = idx + 1


def _text_has_any(
    haystack: str,
    markers: tuple[str, ...] | list[str],
) -> str | None:
    """
    Возвращает первый совпавший маркер (с учётом границы слова —
    см. _marker_matches).
    """
    for marker in markers:
        marker = _normalize(marker)

        if marker and _marker_matches(haystack, marker):
            return marker

    return None


def _text_has_all(
    haystack: str,
    markers: tuple[str, ...] | list[str],
) -> bool:
    """
    True, если ВСЕ маркеры присутствуют в haystack (с учётом
    границы слова — см. _marker_matches).
    """
    for marker in markers:
        marker = _normalize(marker)

        if not marker or not _marker_matches(haystack, marker):
            return False

    return True




