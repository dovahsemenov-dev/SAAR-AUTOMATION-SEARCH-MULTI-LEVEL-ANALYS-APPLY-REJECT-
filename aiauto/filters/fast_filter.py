def detect_extended_target_role(title: str) -> str | None:
    """Возвращает performance / seo / data_bi или None."""
    normalized = _normalize(title)
    if not normalized:
        return None

    for role_name, markers in EXTENDED_TARGET_ROLES.items():
        if _text_has_any(normalized, markers) is not None:
            return role_name

    return None


