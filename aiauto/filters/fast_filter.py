"""
Быстрый детерминированный фильтр вакансий HH.

АРХИТЕКТУРА: WHITELIST-FIRST.

Задача:
    ОТСЕЯТЬ ДОРОГОЙ ОСНОВНОЙ AI-PIPELINE ОТ ВСЕГО, ЧТО НЕ ЯВЛЯЕТСЯ
    ОДНОЗНАЧНОЙ IT-ПРОФЕССИЕЙ.

Раньше здесь был blacklist-first подход: сначала проверяли
маленький список сильных IT-маркеров, а всё, что не попало ни в
whitelist, ни в большой blacklist — уходило в REVIEW_BY_AI и
дальше грузило Qwen. Из-за этого сотни явно нерелевантных вакансий
("Лакировщик", "Скрутчик изделий кабельного производства" и т.п.)
всё равно доходили до модели, просто потому что blacklist не
успевал их поймать по конкретной формулировке.

Новая логика ОБРАТНАЯ:

    явно IT (по whitelist)              -> TARGET
    явно IT (по устойчивой комбинации)   -> TARGET
    явно НЕ IT (принудительный список)   -> HARD_REJECT
    всё остальное                        -> HARD_REJECT

REVIEW_BY_AI как статус в интерфейсе сохранён (используется только
для полностью пустых карточек без title/snippet — данных для
решения физически нет), но перестал быть "свалкой для всего
неоднозначного". Всё неоднозначное теперь REJECT, а не передача
решения дальше по цепочке.

ВАЖНО (сознательное отличие от типового ChatGPT-ТЗ):
    "специалист технической поддержки", "техническая поддержка ПО"
    и подобные formulировки НЕ считаются IT в этом whitelist.
    Пользователь явно решил: техподдержка — это общение с людьми,
    не IT-профессия сама по себе. Пропускается только явный
    IT support / help desk / специалист IT поддержки — это
    осознанное расхождение с обобщённым списком из раздела 20
    типового ТЗ, а не недосмотр.

ВАЖНО (совместимость с config.py):
    config.py импортирует ровно эти два имени:

        DEFAULT_IT_PROTECT_MARKERS
        DEFAULT_FORCE_HARD_REJECT_MARKERS

    Переименовывать их нельзя — это сломает импорт всего проекта
    (см. историю с версией фильтра, где эти константы были
    переименованы без проверки config.py и main.py перестал
    запускаться с ImportError).

ИСПРАВЛЕНИЕ (реальный прогон, ложный APPLY):
Вакансия "Регулировщик (инженер-электроник, тестировщик)" (Казань,
оборонное производство) прошла whitelist и получила TARGET/APPLY.

Причина: в DEFAULT_FORCE_HARD_REJECT_MARKERS был маркер
"электроники" (родительный падеж), а в заголовке стояло
"электроник" (без окончания) — substring-проверка не совпала.
Blacklist не сработал, дошло до whitelist, где слово
"тестировщик" в скобках дало ложный TARGET, хотя по сути роль
целиком производственная (наладка/регулировка оборудования), а
"тестировщик" — вообще не тестировщик ПО.

Решение:
    1) Добавлено само слово "регулировщик" — точечный фикс.
    2) Добавлен отдельный список PRODUCTION_ROLE_MARKERS —
       устойчивые производственные/рабочие специальности, которые
       нередко пишут через запятую вместе с посторонними словами
       в скобках (как в этом случае). Список объединён в
       DEFAULT_FORCE_HARD_REJECT_MARKERS ниже, порядок проверки
       не меняется (blacklist по-прежнему проверяется ДО
       whitelist в classify_fast()).
"""

