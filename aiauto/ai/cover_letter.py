# ============================================================
# Внутренняя защита
# ============================================================

def _validate_generated_letter(
    letter: str,
    facts: list[str],
) -> str:

    letter = _clean_text(letter)

    if not letter:
        raise ValueError(
            "Детерминированный генератор получил пустое письмо."
        )

    lowered = _norm(letter)

    # --------------------------------------------------------
    # Placeholders
    # --------------------------------------------------------

    for placeholder in FORBIDDEN_PLACEHOLDERS:

        if _norm(placeholder) in lowered:

            raise ValueError(
                "В письме обнаружен placeholder: "
                f"{placeholder}"
            )

    # --------------------------------------------------------
    # Опасные заявления
    # --------------------------------------------------------

    for pattern in FORBIDDEN_CLAIM_PATTERNS:

        if re.search(
            pattern,
            lowered,
        ):

            raise ValueError(
                "В детерминированном письме обнаружена "
                "потенциально неподтверждённая формулировка: "
                f"{pattern}"
            )

    # --------------------------------------------------------
    # Факты
    # --------------------------------------------------------

    if facts:

        if not any(
            _norm(fact) in lowered
            for fact in facts
        ):

            raise ValueError(
                "Письмо не содержит ни одного "
                "выбранного подтверждённого факта."
            )

    return letter


