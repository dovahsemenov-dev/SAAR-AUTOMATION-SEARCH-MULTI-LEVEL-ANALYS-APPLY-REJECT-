
"""ai/cover_letter.py

Детерминированная генерация сопроводительного письма.

Qwen НЕ пишет письмо.

Qwen участвует только в выборе подтверждённых фактов
через fact_selector.py.

Письмо формируется исключительно Python-шаблоном.

ИСПРАВЛЕНИЕ (реальный прогон, шаблонность писем):
Раньше generate_cover_letter() собирала письмо из ДВУХ жёстко
зашитых строк (одна — если есть подтверждённые факты, вторая —
если фактов нет). На прогоне из 50+ откликов это означало, что
почти все письма заканчивались буквально одной и той же фразой
("...развиваясь как начинающий специалист..."), что для
рекрутеров, читающих несколько откликов подряд, выглядит как
рассылка под копирку.

Решение: каждое письмо теперь собирается из 4 независимо
выбираемых блоков (приветствие/повод, представление фактов,
"развиваюсь в IT", закрытие), у каждого — несколько вариантов
формулировки. Вариант выбирается ДЕТЕРМИНИРОВАННО по хэшу
(id вакансии + номер блока), а не через random.choice() без
seed — то есть при повторной обработке той же вакансии (если
REPROCESS_VACANCIES=True) письмо не будет каждый раз новым, но
для разных вакансий комбинации почти не повторяются.

Валидация (_validate_generated_letter) не изменилась: любая
формулировка, добавленная в списки ниже, ОБЯЗАНА проходить те
же проверки на placeholder'ы, опасные заявления об опыте и
обязательное упоминание выбранного факта — это гарантируется
тем, что _validate_generated_letter() как вызывалась в самом
конце generate_cover_letter(), так и вызывается сейчас, уже
после сборки письма из случайно выбранных блоков.
"""

from __future__ import annotations

