# ============================================================
# Placeholders
# ============================================================

FORBIDDEN_PLACEHOLDERS = (
    "[ваше имя]",
    "[имя]",
    "<имя>",
    "{имя}",
    "{{имя}}",
    "[название компании]",
    "[название вакансии]",
    "<название компании>",
    "<название вакансии>",
    "[компания]",
    "[вакансия]",
    "<компания>",
    "<вакансия>",
)


# ============================================================
# Потенциально опасные заявления
# ============================================================

FORBIDDEN_CLAIM_PATTERNS = (
    r"\bкоммерческ\w+\s+опыт\b",
    r"\bпрофессиональн\w+\s+опыт\b",
    r"\bопыт\s+работы\b",
    r"\bработал(?:а)?\s+в\s+компани",
    r"\bработал(?:а)?\s+на\s+позици",
    r"\bзанимал(?:а)?\s+должност",
    r"\bнастраивал(?:а)?\b",
    r"\bадминистрировал(?:а)?\b",
    r"\bразрабатывал(?:а)?\b",
    r"\bсоздавал(?:а)?\s+(?:систем|приложен|сервис)",
)


# ============================================================
# Утилиты
# ============================================================

def _clean_text(value: Any) -> str:
    return (
        " ".join(
            str(value or "")
            .replace("\x00", " ")
            .split()
        )
        .strip()
    )


def _norm(value: Any) -> str:
    return (
        _clean_text(value)
        .lower()
        .replace("ё", "е")
    )


def _pick(
    variants: tuple[str, ...],
    seed_key: str,
    slot: str,
) -> str:
    """
    Детерминированный, но хорошо перемешанный выбор варианта из
    списка формулировок. Один и тот же seed_key (обычно —
    id вакансии) + slot (название блока письма) всегда даёт один
    и тот же индекс, но разные вакансии почти никогда не получают
    одинаковую комбинацию всех 4 блоков сразу.

    Намеренно не используется random.choice()/random.seed() —
    не нужно тянуть глобальное состояние random в детерминированный
    генератор, который должен быть воспроизводим и легко
    тестируем без побочных эффектов.
    """

    if not variants:
        return ""

    digest = hashlib.md5(
        f"{seed_key}::{slot}".encode("utf-8")
    ).hexdigest()

    index = int(digest, 16) % len(variants)

    return variants[index]


# ============================================================
# Факты
# ============================================================

def _extract_fact_strings(
    selected_facts: Any,
) -> list[str]:

    result: list[str] = []

    if not isinstance(
        selected_facts,
        list,
    ):
        return result

    for item in selected_facts:

        if isinstance(item, str):

            fact = _clean_text(item)

        elif isinstance(item, dict):

            fact = _clean_text(
                item.get("fact")
                or item.get("text")
            )

        else:

            fact = ""

        if fact and fact not in result:
            result.append(fact)

    return result


def _vacancy_title(
    vacancy: dict,
) -> str:

    return (
        _clean_text(
            vacancy.get("title")
        )
        or "вакансия"
    )


def _company(
    vacancy: dict,
) -> str:

    return _clean_text(
        vacancy.get("company")
    )


def _vacancy_seed(
    vacancy: dict,
) -> str:
    """
    Ключ для детерминированного выбора вариантов письма.
    Приоритет — id вакансии (стабилен между полями карточки).
    Если id почему-то отсутствует — используем title+company,
    чтобы выбор всё равно был воспроизводимым, а не случайным
    при каждом вызове.
    """

    vacancy_id = _clean_text(vacancy.get("id"))

    if vacancy_id:
        return vacancy_id

    return f"{_vacancy_title(vacancy)}::{_company(vacancy)}"


