# Публичный API
# ============================================================

def generate_cover_letter(
    ollama_url: str | None = None,
    model_name: str | None = None,
    vacancy: dict | None = None,
    selected_facts: list[dict] | None = None,
) -> str:
    """
    Генерирует письмо только Python-шаблоном.

    ollama_url/model_name сохранены ради совместимости
    с текущим main.py.

    Письмо собирается из 4 блоков (приветствие, факты [если
    есть], "развиваюсь в IT", закрытие) — вариант каждого блока
    выбирается детерминированно по id вакансии, так что разные
    вакансии почти всегда получают разные комбинации формулировок
    вместо одного и того же текста на каждый отклик.
    """

    vacancy = vacancy or {}

    facts = _extract_fact_strings(
        selected_facts
    )

    title = _vacancy_title(
        vacancy
    )

    company = _company(
        vacancy
    )

    company_part = (
        f" в компании «{company}»"
        if company
        else ""
    )

    seed = _vacancy_seed(vacancy)
    extended_role = detect_extended_target_role(title)

    opener = _pick(OPENERS, seed, "opener").format(
        title=title,
        company_part=company_part,
    )

    # --------------------------------------------------------
    # Есть подтверждённые факты.
    # --------------------------------------------------------

    if facts:

        facts_text = "; ".join(
            facts[:3]
        )

        facts_intro = _pick(
            FACTS_INTROS, seed, "facts_intro"
        ).format(facts_text=facts_text)

        tail_variants = (
            EXTENDED_TAILS_WITH_FACTS
            if extended_role is not None
            else DEVELOPING_TAILS_WITH_FACTS
        )
        tail = _pick(
            tail_variants, seed, "tail"
        )

        closing = _pick(CLOSINGS, seed, "closing")

        letter = " ".join(
            (opener, facts_intro, tail, closing)
        )

    # --------------------------------------------------------
    # Нет подтверждённых фактов.
    # --------------------------------------------------------

    else:

        tail_variants = (
            EXTENDED_TAILS_NO_FACTS
            if extended_role is not None
            else DEVELOPING_TAILS_NO_FACTS
        )
        tail = _pick(
            tail_variants, seed, "tail"
        )

        closing = _pick(CLOSINGS, seed, "closing")

        letter = " ".join(
            (opener, tail, closing)
        )

    return _validate_generated_letter(
        letter,
        facts,
    )


