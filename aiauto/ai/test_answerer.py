def _confirmed_blob(profile_facts: dict) -> str:
    """
    Плоский нижнерегистрый текст всего profile_facts, КРОМЕ
    "explicitly_not_confirmed" и "preferences" (это не факты о
    навыках, а список того, чего точно нет, и служебные настройки —
    их включение дало бы ложные совпадения).
    """

    if not isinstance(profile_facts, dict):
        return ""

    reduced = {
        key: value
        for key, value in profile_facts.items()
        if key not in ("explicitly_not_confirmed", "preferences")
    }

    try:
        return json.dumps(
            reduced,
            ensure_ascii=False,
        ).lower()
    except Exception:
        return str(reduced).lower()


def _extract_advanced_topic_hits(
    question_text: str,
) -> list[str]:
    normalized = _normalize_text(question_text)

    hits = [
        marker
        for marker in ADVANCED_KNOWLEDGE_MARKERS
        if marker in normalized
    ]

    if _IB_TOKEN_RE.search(question_text or ""):
        hits.append("иб")

    return hits


def _topic_is_confirmed(
    topic: str,
    confirmed_blob: str,
) -> bool:
    if topic == "иб":
        return bool(
            _IB_TOKEN_RE.search(confirmed_blob)
            or "информационная безопасность" in confirmed_blob
            or "информационной безопасности" in confirmed_blob
        )

    return topic.strip() in confirmed_blob


def _sentence_has_disclaimer(sentence: str) -> bool:
    if _text_has_any(sentence, _KNOWLEDGE_DISCLAIM_MARKERS):
        return True

    return bool(_DISCLAIM_REVERSED_RE.search(sentence))


def _check_self_assessment_grounding(
    q: dict,
    answer: dict,
    profile_facts: dict,
) -> dict:
    """
    Второй, более общий предохранитель поверх _guard().

    Срабатывает только для open-ответов на вопросы-самооценки,
    которые упоминают "продвинутую" тему из
    ADVANCED_KNOWLEDGE_MARKERS/ИБ. Проверка идёт ПО ПРЕДЛОЖЕНИЯМ:
    утверждение о владении темой считается проблемой, только если
    в ТОМ ЖЕ предложении нет честной оговорки об отсутствии опыта.
    Оговорка в другом предложении ответа больше не "отбеливает"
    ложное утверждение.
    """

    if not isinstance(answer, dict):
        return answer

    if answer.get("mode") != "own_text":
        return answer

    question_text = str(
        q.get("description", "")
    )

    if not _looks_like_self_assessment_question(
        question_text
    ):
        return answer

    advanced_hits = _extract_advanced_topic_hits(
        question_text
    )

    if not advanced_hits:
        return answer

    confirmed_blob = _confirmed_blob(
        profile_facts
    )

    ungrounded_topics = [
        hit
        for hit in advanced_hits
        if not _topic_is_confirmed(hit, confirmed_blob)
    ]

    if not ungrounded_topics:
        return answer

    answer_text = str(answer.get("text", ""))

    if not answer_text.strip():
        return answer

    problem_sentences: list[str] = []

    for sentence in _split_sentences(answer_text):
        normalized_sentence = _normalize_text(sentence)

        if not _text_has_any(
            normalized_sentence,
            _KNOWLEDGE_CLAIM_MARKERS,
        ):
            continue

        if _sentence_has_disclaimer(normalized_sentence):
            continue

        problem_sentences.append(sentence.strip())

    if not problem_sentences:
        return answer

    return {
        "task_id": q["task_id"],
        "mode": "needs_manual_input",
        "solution_ids": [],
        "text": None,
        "reason": (
            "guard: вопрос касается продвинутых тем "
            f"({', '.join(sorted(set(ungrounded_topics)))}), которых нет "
            "в PROFILE_FACTS, а ответ содержит утверждение(-я) о наличии "
            "знаний/опыта/участия без оговорки в том же предложении: "
            + " | ".join(problem_sentences)
        ),
    }


def _collect_enum_leak_tokens(
    data: Any,
) -> set[str]:
    """
    Рекурсивно собирает все строковые значения PROFILE_FACTS,
    похожие на служебный snake_case-код (минимум одно подчёркивание,
    только строчные латинские буквы/цифры) — то есть на внутренние
    ярлыки уровня/статуса вроде "currently_studying",
    "basic_good_theoretical_beginner", а не на обычные слова или
    русский текст.
    """

    tokens: set[str] = set()

    def walk(value: Any) -> None:
        if isinstance(value, dict):
            for item in value.values():
                walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)
        elif isinstance(value, str):
            candidate = value.strip()

            if _SNAKE_CASE_VALUE_RE.match(candidate):
                tokens.add(candidate.lower())

    walk(data)

    return tokens


def _check_enum_leak(
    q: dict,
    answer: dict,
    profile_facts: dict,
) -> dict:
    """
    Последний предохранитель против дословной утечки служебных
    snake_case-значений PROFILE_FACTS (например "currently_studying")
    в ответ кандидата. Правило №9 в промпте запрещает это явно, но
    локальная модель иногда его игнорирует — этот guard не полагается
    на послушание модели, а проверяет фактический текст ответа.

    Ничего не пытается "исправить" — при обнаружении утечки вопрос
    уходит в needs_manual_input, а не отправляется со случайно
    подобранной заменой.
    """

    if not isinstance(answer, dict):
        return answer

    if answer.get("mode") != "own_text":
        return answer

    answer_text = str(answer.get("text", "") or "")

    if not answer_text.strip():
        return answer

    low = answer_text.lower()

    leaked_tokens = sorted(
        token
        for token in _collect_enum_leak_tokens(profile_facts)
        if re.search(rf"\b{re.escape(token)}\b", low)
    )

    if not leaked_tokens:
        return answer

    return {
        "task_id": q["task_id"],
        "mode": "needs_manual_input",
        "solution_ids": [],
        "text": None,
        "reason": (
            "guard: ответ дословно содержит служебное значение "
            "из PROFILE_FACTS вместо обычной формулировки ("
            + ", ".join(leaked_tokens)
            + ")"
        ),
    }


