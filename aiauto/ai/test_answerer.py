# Публичный API
# ============================================================

def _downgrade_open_manual_input(
    q: dict,
    answer: dict,
) -> dict:
    """
    Последний общий предохранитель против потери отклика из-за
    одного неотвеченного открытого вопроса (см. пункт 11 разбора:
    needs_manual_input должен остаться только там, где у
    choice-вопроса действительно нет безопасного варианта).

    Если ЛЮБОЙ guard выше (домен, self-assessment, enum-leak,
    location-leak) в итоге вернул needs_manual_input для вопроса
    типа "open" (свободный текст, без options) — заменяем на
    own_text "-". Оригинальная причина сохраняется в reason, чтобы
    не терять диагностику, но отправка анкеты этим больше не
    блокируется.

    Для "choice" ничего не меняем: там "-" не является валидным
    вариантом ответа, и needs_manual_input там оставлен намеренно.
    """

    if not isinstance(answer, dict):
        return answer

    if answer.get("mode") != "needs_manual_input":
        return answer

    if q.get("type") == "choice" or q.get("options"):
        return answer

    original_reason = str(answer.get("reason", "")).strip()

    return {
        "task_id": q["task_id"],
        "mode": "own_text",
        "solution_ids": [],
        "text": "-",
        "reason": (
            "открытый вопрос без безопасного факта — "
            "автоматически заменено на прочерк "
            f"(исходная причина: {original_reason})"
            if original_reason
            else "открытый вопрос без безопасного факта — "
            "автоматически заменено на прочерк"
        ),
    }


def answer_test_questions(
    ollama_url: str,
    model_name: str,
    vacancy: dict,
    profile_facts: dict,
    questions: list[dict],
) -> list[dict]:
    """
    Основная функция.

    questions:

        {
            "task_id": int,
            "description": str,
            "type": "choice" | "open",
            "options": [
                {
                    "id": str,
                    "text": str
                }
            ]
        }

    Для choice:
        "свой вариант" может присутствовать
        как обычный option с id="open".

    Для open:
        options=[].

    Возвращает ответы в том же порядке.
    """

    answers: list[dict] = []

    for q in questions:

        # ----------------------------------------------------
        # Детерминированная часть (домены, личные вопросы,
        # местоположение, офисный формат, зарплата, telegram,
        # переезд, карьерное направление)
        # ----------------------------------------------------

        deterministic = _deterministic_answer(
            q,
            profile_facts,
        )

        if deterministic is not None:
            answers.append(
                deterministic
            )
            continue

        # ----------------------------------------------------
        # LLM
        # ----------------------------------------------------

        prior_answers = [
            {
                "task_id": item.get("task_id"),
                "question": next(
                    (
                        previous_q
                        for previous_q in questions
                        if previous_q.get("task_id") == item.get("task_id")
                    ),
                    {},
                ),
                "answer": item,
            }
            for item in answers
            if isinstance(item, dict)
        ]

        llm_answer = _ask_llm(
            ollama_url,
            model_name,
            q,
            profile_facts,
            vacancy,
            prior_answers=prior_answers,
        )

        # ----------------------------------------------------
        # Guard (домены из фиксированного списка)
        # ----------------------------------------------------

        guarded = _guard(
            llm_answer,
            q,
        )

        # ----------------------------------------------------
        # Guard для вопросов-самооценок (по предложениям)
        # ----------------------------------------------------

        guarded = _check_self_assessment_grounding(
            q,
            guarded,
            profile_facts,
        )

        # ----------------------------------------------------
        # ДОБАВЛЕНО (3): guard против дословной утечки
        # служебных snake_case-значений PROFILE_FACTS
        # ----------------------------------------------------

        guarded = _check_enum_leak(
            q,
            guarded,
            profile_facts,
        )

        # ----------------------------------------------------
        # ДОБАВЛЕНО (6): guard против выдуманного города/
        # готовности к офису, если вопрос всё же дошёл до LLM
        # ----------------------------------------------------

        guarded = _check_location_leak(
            q,
            guarded,
            profile_facts,
        )

        # ----------------------------------------------------
        # ИСПРАВЛЕНИЕ (11): финальная нормализация.
        #
        # needs_manual_input оправдан только там, где вообще
        # невозможно безопасно ответить — то есть у choice-
        # вопроса нет ни подходящего варианта, ни варианта
        # "свой ответ"/"не указано". Для открытых (open)
        # вопросов всегда есть безопасный дефолт — "-", и любой
        # guard выше, который так и не смог подтвердить факт,
        # не должен блокировать отправку всей анкеты из-за
        # одного неизвестного открытого вопроса.
        # ----------------------------------------------------

        guarded = _downgrade_open_manual_input(
            q,
            guarded,
        )

        answers.append(
            guarded
        )

    return answers


def has_manual_input_required(
    answers: list[dict],
) -> bool:
    return any(
        answer.get("mode")
        == "needs_manual_input"
        for answer in answers
    )


def manual_input_reasons(
    answers: list[dict],
    questions: list[dict],
) -> list[str]:
    """
    Человекочитаемый список вопросов,
    которые нельзя безопасно закрыть автоматически.
    """

    by_id = {
        q["task_id"]: q.get(
            "description",
            f"вопрос #{q['task_id']}",
        )
        for q in questions
    }

    reasons: list[str] = []

    for answer in answers:

        if (
            answer.get("mode")
            != "needs_manual_input"
        ):
            continue

        task_id = answer.get(
            "task_id"
        )

        question_text = by_id.get(
            task_id,
            f"вопрос #{task_id}",
        )

        reason = answer.get(
            "reason",
            "неизвестная причина",
        )

        reasons.append(
            f"{question_text} — {reason}"
        )

    return reasons