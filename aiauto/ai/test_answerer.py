def _pick_minimum_salary_option(
    options: list[dict],
) -> dict | None:
    best_option = None
    best_low = None

    for opt in options:
        rng = _parse_salary_range(opt.get("text", ""))

        if rng is None:
            continue

        low, _high = rng

        if best_low is None or low < best_low:
            best_low = low
            best_option = opt

    return best_option


def _match_preference(
    q: dict,
    prefs: dict,
) -> dict | None:
    """
    Только явное сопоставление с preferences.

    Ничего не угадываем — кроме одного явно разрешённого
    исключения: зарплатный fallback (см. ниже), потому что это
    не "угадывание факта о кандидате", а прямая, явно заданная в
    preferences.salary_policy инструкция пользователя.
    """

    text = str(
        q.get("description", "")
    ).lower()

    options = q.get("options", [])

    # --------------------------------------------------------
    # Зарплата
    # --------------------------------------------------------

    if _looks_like_salary_question(text):
        salary = (
            prefs.get("salary_expectation_rub")
            or {}
        )

        target = salary.get("from")

        # ----------------------------------------------------
        # ДОБАВЛЕНО (4): open-вопрос без вариантов — раньше сюда
        # всё равно уходила LLM (эта ветка возвращала None) и
        # либо выдумывала конкретную цифру, либо генерировала
        # бессмыслицу. Теперь для open-вопросов о зарплате модель
        # вообще не вызывается — ответ строится детерминированно.
        # ----------------------------------------------------
        if not options:
            if target is not None:
                return {
                    "task_id": q["task_id"],
                    "mode": "own_text",
                    "solution_ids": [],
                    "text": (
                        "Ориентируюсь на заработную плату "
                        f"от {int(target)} руб."
                    ),
                    "reason": (
                        "preferences.salary_expectation_rub"
                    ),
                }

            salary_policy = (
                prefs.get("salary_policy") or {}
            )

            policy_mode = str(
                salary_policy.get("mode", "")
            ).strip().lower()

            policy_fallback = str(
                salary_policy.get("fallback", "")
            ).strip().lower()

            if (
                policy_mode == "not_a_priority"
                or policy_fallback == "minimum"
            ):
                return {
                    "task_id": q["task_id"],
                    "mode": "own_text",
                    "solution_ids": [],
                    "text": (
                        "Точной фиксированной суммы у меня "
                        "нет — зарплата не является для меня "
                        "приоритетом на данном этапе. Готов "
                        "обсудить конкретный уровень на "
                        "собеседовании, исходя из вилки, "
                        "предложенной вакансией."
                    ),
                    "reason": (
                        "preferences.salary_policy: честный "
                        "ответ без выдуманной цифры (открытый "
                        "вопрос, точной суммы в preferences нет)"
                    ),
                }

            return None

        # ----------------------------------------------------
        # Choice-вопрос с вариантами (вилками) — как раньше.
        # ----------------------------------------------------
        if target is not None:
            for opt in options:
                rng = _parse_salary_range(
                    opt.get("text", "")
                )

                if rng is None:
                    continue

                low, high = rng

                if low <= target <= (
                    high
                    if high is not None
                    else float("inf")
                ):
                    return {
                        "task_id": q["task_id"],
                        "mode": "choice",
                        "solution_ids": [
                            opt["id"]
                        ],
                        "text": None,
                        "reason": (
                            "совпадение с "
                            "preferences.salary_expectation_rub"
                        ),
                    }

            return None

        salary_policy = prefs.get("salary_policy") or {}

        if str(
            salary_policy.get("fallback", "")
        ).strip().lower() == "minimum":
            best_option = _pick_minimum_salary_option(options)

            if best_option is not None:
                return {
                    "task_id": q["task_id"],
                    "mode": "choice",
                    "solution_ids": [
                        best_option["id"]
                    ],
                    "text": None,
                    "reason": (
                        "preferences.salary: конкретной зарплатной "
                        "цифры нет, зарплата не приоритет — "
                        "выбран минимальный вариант"
                    ),
                }

        return None

    # --------------------------------------------------------
    # Telegram / контакты
    # --------------------------------------------------------

    if _looks_like_telegram_question(text):
        telegram = prefs.get("telegram")

        if telegram:
            return {
                "task_id": q["task_id"],
                "mode": "own_text",
                "solution_ids": [],
                "text": str(telegram),
                "reason": "preferences.telegram",
            }

        return None

    # --------------------------------------------------------
    # Переезд
    # --------------------------------------------------------

    if (
        "переезд" in text
        or "переехать" in text
        or "релокац" in text
    ):
        value = prefs.get(
            "willing_to_relocate"
        )

        if value is None:
            return None

        opt = (
            _positive_option(q)
            if value
            else _negative_option(q)
        )

        if opt is None:
            return None

        return {
            "task_id": q["task_id"],
            "mode": "choice",
            "solution_ids": [
                opt["id"]
            ],
            "text": None,
            "reason": (
                "preferences.willing_to_relocate"
            ),
        }

    # --------------------------------------------------------
    # Карьерное направление
    # --------------------------------------------------------

    if (
        "развива" in text
        or "направлени" in text
        or "карьер" in text
    ):
        wanted = (
            prefs.get(
                "career_growth_options"
            )
            or []
        )

        for substring in wanted:
            substring_low = str(
                substring
            ).lower()

            for opt in options:
                if substring_low in str(
                    opt.get("text", "")
                ).lower():
                    return {
                        "task_id": q["task_id"],
                        "mode": "choice",
                        "solution_ids": [
                            opt["id"]
                        ],
                        "text": None,
                        "reason": (
                            "совпадение с "
                            "preferences."
                            "career_growth_options"
                        ),
                    }

        return None

    return None


