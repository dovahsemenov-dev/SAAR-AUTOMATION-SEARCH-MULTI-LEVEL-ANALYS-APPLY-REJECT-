def _check_location_question(
    q: dict,
    profile_facts: dict,
) -> dict | None:
    """
    Отвечает на вопрос "где вы территориально проживаете"
    напрямую из profile_facts["location"]["city"], без LLM.

    Возвращает None, если вопрос не про местоположение или город
    в PROFILE_FACTS не задан — в последнем случае вопрос уходит
    по обычной ветке дальше (в LLM или needs_manual_input), а не
    получает выдуманный город.
    """

    question_text = str(q.get("description", ""))

    if not _looks_like_location_question(question_text):
        return None

    location = profile_facts.get("location")

    if not isinstance(location, dict):
        return None

    city = str(location.get("city", "")).strip()

    if not city:
        return None

    country = str(location.get("country", "")).strip() or "Россия"

    return {
        "task_id": q["task_id"],
        "mode": "own_text",
        "solution_ids": [],
        "text": f"Я проживаю в городе {city}, {country}.",
        "reason": "profile_facts.location.city",
    }


# ИСПРАВЛЕНИЕ: вопросы про образование отвечаются напрямую из
# profile_facts["education"], без LLM — см. комментарий у
# _EDUCATION_QUESTION_MARKERS. Ничего, кроме того, что реально
# есть в PROFILE_FACTS (статус обучения, курс, специальность), не
# добавляется: учреждение и год окончания, которых в фактах нет,
# в текст не попадают.
def _check_education_question(
    q: dict,
    profile_facts: dict,
) -> dict | None:
    question_text = str(q.get("description", ""))

    if not _looks_like_education_question(question_text):
        return None

    education = profile_facts.get("education")

    if not isinstance(education, dict):
        return None

    status = str(education.get("status", "")).strip()
    specialty = str(education.get("specialty", "")).strip()
    course = education.get("course")

    if not specialty:
        return None

    if status == "currently_studying":
        course_clause = (
            f" на {course} курсе"
            if course
            else ""
        )
        text = (
            f"В настоящий момент учусь{course_clause} по "
            f"специальности «{specialty}»."
        )
    else:
        text = f"Специальность: «{specialty}»."

    return {
        "task_id": q["task_id"],
        "mode": "own_text",
        "solution_ids": [],
        "text": text,
        "reason": "profile_facts.education",
    }


# ИСПРАВЛЕНИЕ: чисто служебные благодарственные фразы в конце
# анкеты не требуют содержательного ответа и уж точно не должны
# провоцировать LLM рассуждать про переезд/город/офис — см.
# комментарий у _ACKNOWLEDGEMENT_MARKERS.
def _check_acknowledgement_message(
    q: dict,
) -> dict | None:
    question_text = str(q.get("description", ""))

    if not _looks_like_acknowledgement_message(question_text):
        return None

    return {
        "task_id": q["task_id"],
        "mode": "own_text",
        "solution_ids": [],
        "text": (
            "Спасибо за рассмотрение моего отклика. "
            "Буду ждать обратной связи."
        ),
        "reason": "служебное сообщение — короткий шаблонный ответ",
    }


def _check_office_format_question(
    q: dict,
    profile_facts: dict,
) -> dict | None:
    """
    Отвечает на вопросы о готовности к очному/офисному формату
    работы в конкретном городе, без LLM.

    Логика:
        1. Пытаемся извлечь из текста вопроса упомянутый город
           (например "офис в г. Пенза").
        2. Если город распознан и входит в
           preferences.office_locations_allowed — честное "да".
        3. Если город распознан и НЕ входит в список — честный
           отказ от офиса в этом городе, с явной оговоркой про
           готовность к удалёнке (если remote_ok=True).
        4. Если город из текста извлечь не удалось, но
           office_locations_allowed задан — общий честный ответ
           без привязки к конкретному городу.
        5. Если office_locations_allowed вообще не задан (пусто)
           — возвращаем None: решение отдаётся обычной ветке
           preference-вопросов (needs_manual_input), а не
           придумывается на пустом месте.
    """

    question_text = str(q.get("description", ""))

    if not _looks_like_office_format_question(question_text):
        return None

    prefs = profile_facts.get("preferences") or {}

    allowed_cities = prefs.get("office_locations_allowed") or []
    allowed_cities = [
        str(city).strip()
        for city in allowed_cities
        if str(city).strip()
    ]

    if not allowed_cities:
        return None

    remote_ok = bool(prefs.get("remote_ok", False))
    allowed_lower = {city.lower() for city in allowed_cities}
    allowed_joined = " или ".join(allowed_cities)

    mentioned_city = _extract_mentioned_city(question_text)

    if mentioned_city is not None:
        if mentioned_city.lower() in allowed_lower:
            return {
                "task_id": q["task_id"],
                "mode": "own_text",
                "solution_ids": [],
                "text": (
                    f"Да, готов к такому формату — офис в "
                    f"{mentioned_city} мне подходит."
                ),
                "reason": (
                    "город из вопроса совпал с "
                    "preferences.office_locations_allowed"
                ),
            }

        remote_clause = (
            " В удалённом формате готов работать из любого города."
            if remote_ok
            else ""
        )

        return {
            "task_id": q["task_id"],
            "mode": "own_text",
            "solution_ids": [],
            "text": (
                f"К сожалению, к очному формату в "
                f"{mentioned_city} не готов — рассматриваю офис "
                f"только в {allowed_joined}."
                f"{remote_clause}"
            ),
            "reason": (
                "город из вопроса отсутствует в "
                "preferences.office_locations_allowed"
            ),
        }

    # Город из текста вопроса не распознан — общий честный ответ
    # без привязки к конкретному месту, без угадывания.
    remote_clause = (
        " В остальных случаях рассматриваю только удалённый формат."
        if remote_ok
        else ""
    )

    return {
        "task_id": q["task_id"],
        "mode": "own_text",
        "solution_ids": [],
        "text": (
            f"Готов к очному офисному формату только в "
            f"{allowed_joined}.{remote_clause}"
        ),
        "reason": (
            "конкретный город в вопросе не распознан — "
            "дан общий ответ по "
            "preferences.office_locations_allowed"
        ),
    }


