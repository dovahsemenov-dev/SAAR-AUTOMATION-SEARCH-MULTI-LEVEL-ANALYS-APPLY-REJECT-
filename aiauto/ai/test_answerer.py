# Детерминированный слой
# ============================================================

def _deterministic_answer(
    q: dict,
    profile_facts: dict,
) -> dict | None:
    """
    Отвечает без LLM там, где ответ можно получить
    однозначно.

    None означает:
        передать вопрос LLM.
    """

    question = str(
        q.get("description", "")
    )

    # --------------------------------------------------------
    # 0. Служебные благодарственные сообщения ("спасибо за ваше
    #    время...") — не вопрос по существу, короткий шаблон,
    #    LLM не вызывается вообще.
    # --------------------------------------------------------

    acknowledgement_answer = _check_acknowledgement_message(q)

    if acknowledgement_answer is not None:
        return acknowledgement_answer

    # --------------------------------------------------------
    # 1. Неподтверждённый домен.
    #
    #    ИСПРАВЛЕНО: раньше этот блок одинаково реагировал на
    #    "Есть ли у вас опыт работы с 1С?" (вопрос про факт о
    #    кандидате) и на "Опишите план тестирования в 1С"
    #    (техническая reasoning-задача, которая просто
    #    упоминает 1С в условии). Теперь блок применяется
    #    только к вопросам про СОБСТВЕННЫЙ опыт кандидата —
    #    reasoning-задачи со словом "1С" в условии сюда не
    #    попадают и уходят к LLM как обычно (см. правило 8 в
    #    _build_prompt()).
    # --------------------------------------------------------

    domain = _find_unconfirmed_domain(
        question
    )

    if (
        domain is not None
        and _looks_like_own_experience_question(question)
    ):

        negative = _negative_option(q)

        if negative is not None:
            return {
                "task_id": q["task_id"],
                "mode": "choice",
                "solution_ids": [
                    negative["id"]
                ],
                "text": None,
                "reason": (
                    f"домен '{domain}' "
                    "явно не подтверждён"
                ),
            }

        # Открытый (own_text) вопрос про собственный опыт с
        # неподтверждённым доменом — отвечаем честным "нет"
        # напрямую, без LLM и без ухода в ручной ввод.
        if not q.get("options"):
            return {
                "task_id": q["task_id"],
                "mode": "own_text",
                "solution_ids": [],
                "text": f"Опыта работы с {domain} у меня нет.",
                "reason": (
                    f"домен '{domain}' явно не подтверждён — "
                    "открытый вопрос про собственный опыт"
                ),
            }

        # Есть только option'ы без явного "нет" (например
        # только "свой вариант") — вопрос передаём дальше,
        # guard всё равно не позволит модели подтвердить
        # неподтверждённый домен.

    # --------------------------------------------------------
    # 2. Личный опыт/увлечения/биография вне работы (ДОБАВЛЕНО
    #    (5), расширено достижениями/языками) — PROFILE_FACTS
    #    не содержит таких данных в принципе, поэтому любой
    #    конкретный ответ LLM тут — выдумка. Раньше уходило в
    #    needs_manual_input и блокировало отправку всей анкеты;
    #    теперь для открытых вопросов без такого факта
    #    универсальный безопасный ответ — "-".
    #    Проверяется раньше общего preference-гейта, так как
    #    это не то же самое, что "предпочтение кандидата".
    # --------------------------------------------------------

    if _looks_like_personal_life_question(question):
        return {
            "task_id": q["task_id"],
            "mode": "own_text",
            "solution_ids": [],
            "text": "-",
            "reason": (
                "вопрос касается личного опыта/увлечений/"
                "достижений кандидата вне работы, которых нет "
                "в PROFILE_FACTS — вместо выдумки или ручного "
                "ввода используется универсальный прочерк"
            ),
        }

    # --------------------------------------------------------
    # 3. Образование — отвечаем напрямую из
    #    profile_facts["education"], LLM не вызывается, чтобы
    #    не получить утечку служебного значения
    #    ("currently_studying") или выдуманное учреждение.
    # --------------------------------------------------------

    education_answer = _check_education_question(q, profile_facts)

    if education_answer is not None:
        return education_answer

    # --------------------------------------------------------
    # 4. Город проживания (ДОБАВЛЕНО (6)) — отвечаем напрямую
    #    из profile_facts["location"]["city"], LLM не вызывается,
    #    чтобы не получить выдуманный город.
    # --------------------------------------------------------

    location_answer = _check_location_question(q, profile_facts)

    if location_answer is not None:
        return location_answer

    # --------------------------------------------------------
    # 5. Готовность к офисному формату в конкретном городе
    #    (ДОБАВЛЕНО (6)) — сверяем упомянутый в вопросе город с
    #    preferences.office_locations_allowed, LLM не вызывается.
    # --------------------------------------------------------

    office_format_answer = _check_office_format_question(
        q,
        profile_facts,
    )

    if office_format_answer is not None:
        return office_format_answer

    # --------------------------------------------------------
    # 6. Telegram / контакты и предпочтения (зарплата, переезд,
    #    карьерное направление) — единая точка входа через
    #    _match_preference().
    # --------------------------------------------------------

    is_preference_like = (
        _looks_like_preference_question(question)
        or _looks_like_telegram_question(question)
    )

    if is_preference_like:
        prefs = (
            profile_facts.get(
                "preferences"
            )
            or {}
        )

        matched = _match_preference(
            q,
            prefs,
        )

        if matched is not None:
            return matched

        return {
            "task_id": q["task_id"],
            "mode": "needs_manual_input",
            "solution_ids": [],
            "text": None,
            "reason": (
                "вопрос относится к предпочтению "
                "кандидата, но соответствующее "
                "значение отсутствует в "
                "profile_facts['preferences']"
            ),
        }

    return None


# ============================================================
# LLM prompt
# ============================================================

def _build_prompt(
    q: dict,
    profile_facts: dict,
    vacancy: dict,
    prior_answers: list[dict] | None = None,
) -> str:

    facts_json = json.dumps(
        profile_facts,
        ensure_ascii=False,
        indent=2,
    )

    options_json = json.dumps(
        q.get("options", []),
        ensure_ascii=False,
        indent=2,
    )

    question_type = q.get(
        "type",
        "choice",
    )

    prior_answers = prior_answers or []
    prior_lines = []
    for previous in prior_answers:
        if not isinstance(previous, dict):
            continue
        previous_question = previous.get("question", {})
        previous_answer = previous.get("answer", {})
        previous_text = ""

        if isinstance(previous_answer, dict):
            mode = str(previous_answer.get("mode", "")).strip()
            if mode == "own_text":
                previous_text = str(previous_answer.get("text", "")).strip()
            elif mode == "choice":
                ids = previous_answer.get("solution_ids", [])
                if not isinstance(ids, list):
                    ids = [ids]
                id_set = {str(value) for value in ids}
                for option in previous_question.get("options", []):
                    if (
                        isinstance(option, dict)
                        and str(option.get("id", "")) in id_set
                    ):
                        text = str(option.get("text", "")).strip()
                        if text:
                            prior_lines.append(
                                f"- Вопрос {previous.get('task_id')}: "
                                f"{previous_question.get('description', '')}\n"
                                f"  Ответ: {text}"
                            )
                continue
            elif mode == "needs_manual_input":
                previous_text = str(previous_answer.get("reason", "")).strip()

        if previous_text:
            prior_lines.append(
                f"- Вопрос {previous.get('task_id')}: "
                f"{previous_question.get('description', '')}\n"
                f"  Ответ: {previous_text}"
            )

    prior_answers_text = (
        "\n".join(prior_lines)
        if prior_lines
        else "(предыдущих ответов нет)"
    )

    return f"""
Ты отвечаешь на дополнительный вопрос
скрининг-анкеты вакансии HH.ru от лица кандидата.

ТИП ВОПРОСА:
{question_type}

ВОПРОС:
{q.get("description", "")}

ДОСТУПНЫЕ ВАРИАНТЫ:
{options_json}

PROFILE_FACTS:
{facts_json}

ВАКАНСИЯ:
{vacancy.get("title", "")} —
{vacancy.get("company", "")}

ПРЕДЫДУЩИЕ ОТВЕТЫ ЭТОЙ ЖЕ АНКЕТЫ:
{prior_answers_text}

ВАЖНО ДЛЯ СОГЛАСОВАННОСТИ:
- Учитывай предыдущие ответы этой же анкеты.
- Не давай ответ, который прямо противоречит уже данному ответу.
- Если вопросы относятся к разным технологиям/разным фактам, не
  считай их противоречием только из-за похожей формулировки.
- Если для согласованного ответа требуется неизвестный персональный
  факт или предпочтение, верни needs_manual_input.

ЖЁСТКИЕ ПРАВИЛА:

1. PROFILE_FACTS — единственный источник
   информации о кандидате.

2. НЕЛЬЗЯ придумывать:
   - опыт;
   - коммерческий опыт;
   - технологии;
   - сертификаты;
   - образование;
   - зарплату;
   - работодателей;
   - проекты;
   - сроки;
   - стаж;
   - готовность к переезду;
   - карьерные предпочтения;
   - участие в мероприятиях, соревнованиях, пет-проектах;
   - город проживания или готовность к офису в конкретном городе.

3. Если вопрос ТИПА "choice" относится к
   предпочтению кандидата (зарплата, переезд,
   формат работы и т.п.), а подходящего
   preference и подходящего варианта ответа
   нет — вернуть:
   {{
       "mode": "needs_manual_input",
       "reason": "..."
   }}
   needs_manual_input используй ТОЛЬКО для
   choice-вопросов, где действительно нет ни
   одного безопасного варианта. Для open-
   вопросов needs_manual_input запрещён —
   см. правило 3b.

3b. Если вопрос ТИПА "open" (свободный текст)
    касается личного факта/биографии/увлечения/
    достижений/уровня языка и т.п., а нужных
    данных в PROFILE_FACTS нет — НЕ придумывай
    факт и НЕ возвращай needs_manual_input.
    Верни:
    {{
        "mode": "own_text",
        "text": "-"
    }}
    "-" — универсальный безопасный ответ на
    любой открытый вопрос, факта для которого
    нет в PROFILE_FACTS.

4. Если вопрос относится к факту кандидата
   и факт подтверждён — можно использовать
   его.

5. Если факт НЕ подтверждён — нельзя
   превращать отсутствие информации
   в положительный ответ. Если честного ответа
   "нет/не имею" достаточно — используй его, а не
   расплывчатое "базовое понимание"/"немного знаком".
   Это касается и вопросов вида "есть ли у вас опыт
   с X" — честное "нет" ты формулируешь сам, не
   уходя в needs_manual_input.

6. Для choice:
   solution_ids должен содержать ТОЛЬКО
   id существующего варианта.

7. Для open:
   mode="own_text", а text должен быть
   коротким, конкретным и честным.

8. Для технической reasoning-задачи
   (например SQL, тест-кейс, чек-лист,
   баг-репорт, план тестирования конкретной
   системы) реши задачу самостоятельно, если
   она не требует выдумывания персональных
   данных кандидата. Упоминание в условии
   задачи технологии/системы, которой нет в
   PROFILE_FACTS (например "опишите план
   тестирования в 1С"), — это НЕ вопрос про
   опыт кандидата с этой технологией, а
   условие задачи. Такие задачи нужно решать
   по существу, а не через needs_manual_input
   и не отказываясь упоминать саму технологию
   из условия в тексте решения.

9. Не выводи JSON-ключи вроде:
   currently_studying,
   is_it_role,
   salary_expectation_rub
   в качестве ответа кандидата.

10. Не добавляй пояснения вне JSON.

Верни строго один из форматов:

CHOICE:
{{
    "mode": "choice",
    "solution_ids": ["ID"]
}}

OPEN:
{{
    "mode": "own_text",
    "text": "короткий ответ"
}}

MANUAL:
{{
    "mode": "needs_manual_input",
    "reason": "почему нельзя ответить автоматически"
}}
""".strip()


# ============================================================
# LLM
# ============================================================

def _ask_llm(
    ollama_url: str,
    model_name: str,
    q: dict,
    profile_facts: dict,
    vacancy: dict,
    prior_answers: list[dict] | None = None,
) -> dict:

    result = ask_json(
        ollama_url,
        model_name,
        _build_prompt(
            q,
            profile_facts,
            vacancy,
            prior_answers=prior_answers,
        ),
    )

    if not isinstance(result, dict):
        return {
            "task_id": q["task_id"],
            "mode": "needs_manual_input",
            "solution_ids": [],
            "text": None,
            "reason": "LLM вернул не JSON",
        }

    mode = str(
        result.get("mode", "")
    ).strip()

    # --------------------------------------------------------
    # choice
    # --------------------------------------------------------

    if mode == "choice":

        raw_ids = result.get(
            "solution_ids",
            [],
        )

        if not isinstance(
            raw_ids,
            list,
        ):
            raw_ids = []

        raw_ids = [
            str(item)
            for item in raw_ids
        ]

        valid_ids = {
            str(opt["id"])
            for opt in q.get(
                "options",
                [],
            )
        }

        ids = [
            item
            for item in raw_ids
            if item in valid_ids
        ]

        if not ids:
            return {
                "task_id": q["task_id"],
                "mode": "needs_manual_input",
                "solution_ids": [],
                "text": None,
                "reason": (
                    "LLM выбрал несуществующий "
                    "вариант"
                ),
            }

        return {
            "task_id": q["task_id"],
            "mode": "choice",
            "solution_ids": ids,
            "text": None,
            "reason": "LLM",
        }

    # --------------------------------------------------------
    # own_text
    # --------------------------------------------------------

    if mode == "own_text":

        text = str(
            result.get(
                "text",
                "",
            )
        ).strip()

        if not text:
            return {
                "task_id": q["task_id"],
                "mode": "needs_manual_input",
                "solution_ids": [],
                "text": None,
                "reason": (
                    "LLM вернул пустой own_text"
                ),
            }

        return {
            "task_id": q["task_id"],
            "mode": "own_text",
            "solution_ids": [],
            "text": text,
            "reason": "LLM",
        }

    # --------------------------------------------------------
    # manual
    # --------------------------------------------------------

    return {
        "task_id": q["task_id"],
        "mode": "needs_manual_input",
        "solution_ids": [],
        "text": None,
        "reason": str(
            result.get(
                "reason",
                "LLM не смог безопасно ответить",
            )
        ),
    }


# ============================================================
# Guard
# ============================================================

def _guard(
    answer: dict,
    q: dict,
) -> dict:
    """
    Последний детерминированный предохранитель.

    LLM может ошибиться.
    Guard не доверяет положительному ответу
    на явно неподтверждённый домен.
    """

    domain = _find_unconfirmed_domain(
        q.get("description", "")
    )

    if domain is None:
        return answer

    # --------------------------------------------------------
    # choice
    # --------------------------------------------------------

    if answer.get("mode") == "choice":

        positive = _positive_option(q)

        if (
            positive is not None
            and positive["id"]
            in answer.get(
                "solution_ids",
                [],
            )
        ):
            negative = _negative_option(q)

            if negative is not None:
                return {
                    "task_id": q["task_id"],
                    "mode": "choice",
                    "solution_ids": [
                        negative["id"]
                    ],
                    "text": None,
                    "reason": (
                        "guard: положительный "
                        f"ответ переопределён, "
                        f"домен '{domain}' "
                        "не подтверждён"
                    ),
                }

            return {
                "task_id": q["task_id"],
                "mode": "needs_manual_input",
                "solution_ids": [],
                "text": None,
                "reason": (
                    "guard: LLM подтвердил "
                    f"неподтверждённый домен "
                    f"'{domain}', а негативного "
                    "варианта нет"
                ),
            }

    # --------------------------------------------------------
    # own_text
    #
    # ИСПРАВЛЕНО: раньше этот блок блокировал ЛЮБОЙ own_text-
    # ответ, который просто упоминает слово из
    # _KNOWN_UNCONFIRMED_SYNONYMS — включая решения технических
    # reasoning-задач ("опишите план тестирования в 1С",
    # "сформулируйте уточняющие вопросы по ошибке в 1С"), где
    # упоминание домена в ответе неизбежно и не означает, что
    # модель приписала кандидату несуществующий опыт. Теперь
    # guard реагирует только тогда, когда сам ВОПРОС спрашивает
    # про собственный опыт кандидата — только там повторение
    # домена в ответе действительно может быть скрытым
    # подтверждением опыта.
    # --------------------------------------------------------

    if (
        answer.get("mode") == "own_text"
        and answer.get("text")
        and _looks_like_own_experience_question(
            q.get("description", "")
        )
    ):
        low = str(
            answer["text"]
        ).lower()

        synonyms = (
            _KNOWN_UNCONFIRMED_SYNONYMS[
                domain
            ]
        )

        if any(
            synonym.lower() in low
            for synonym in synonyms
        ):
            return {
                "task_id": q["task_id"],
                "mode": "own_text",
                "solution_ids": [],
                "text": f"Опыта работы с {domain} у меня нет.",
                "reason": (
                    "guard: own_text "
                    f"упоминал неподтверждённый "
                    f"домен '{domain}' как собственный опыт — "
                    "заменено на честное 'нет'"
                ),
            }

    return answer


# ============================================================
# ДОБАВЛЕНО (6): guard против выдуманного города/готовности
# к офису, если LLM всё же был вызван (например, из-за
# формулировки, которую детерминированные маркеры не покрыли).
# ============================================================

def _check_location_leak(
    q: dict,
    answer: dict,
    profile_facts: dict,
) -> dict:
    """
    Подстраховка на случай, если вопрос про местоположение или
    офисный формат не был перехвачен детерминированными
    обработчиками выше (например, из-за новой формулировки) и
    ушёл в LLM. Если own_text-ответ LLM называет город, который
    не совпадает ни с profile_facts["location"]["city"], ни с
    одним из preferences.office_locations_allowed — это, скорее
    всего, выдумка, и вопрос переводится в needs_manual_input.
    """

    if not isinstance(answer, dict):
        return answer

    if answer.get("mode") != "own_text":
        return answer

    question_text = str(q.get("description", ""))

    is_location_like = (
        _looks_like_location_question(question_text)
        or _looks_like_office_format_question(question_text)
    )

    if not is_location_like:
        return answer

    answer_text = str(answer.get("text", "") or "")

    if not answer_text.strip():
        return answer

    known_city = str(
        (profile_facts.get("location") or {}).get("city", "")
    ).strip().lower()

    allowed_cities = (
        (profile_facts.get("preferences") or {}).get(
            "office_locations_allowed"
        )
        or []
    )

    known_cities = {known_city} | {
        str(city).strip().lower()
        for city in allowed_cities
        if str(city).strip()
    }
    known_cities.discard("")

    mentioned_city = _extract_mentioned_city(answer_text)

    if mentioned_city is None:
        return answer

    if mentioned_city.lower() in known_cities:
        return answer

    return {
        "task_id": q["task_id"],
        "mode": "needs_manual_input",
        "solution_ids": [],
        "text": None,
        "reason": (
            "guard: own_text упоминает город "
            f"'{mentioned_city}', который не совпадает с "
            "profile_facts['location']['city'] и не входит в "
            "preferences.office_locations_allowed — похоже на "
            "выдумку"
        ),
    }


