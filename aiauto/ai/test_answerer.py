def _normalize_text(text: str) -> str:
    return " ".join(
        str(text or "")
        .replace("\xa0", " ")
        .split()
    ).strip().lower()


def _split_sentences(text: str) -> list[str]:
    parts = re.split(r"(?<=[.!?])\s+", str(text or "").strip())
    return [p for p in parts if p.strip()]


def _parse_salary_range(
    text: str,
) -> tuple[float, float | None] | None:
    """
    Примеры:

        40.000-60.000 -> (40000, 60000)
        100.000+      -> (100000, None)
        40 000 – 60 000
    """

    cleaned = (
        str(text or "")
        .replace(" ", "")
        .replace(".", "")
        .replace(",", "")
        .replace("–", "-")
        .replace("—", "-")
    )

    if "+" in cleaned:
        num = "".join(
            ch for ch in cleaned
            if ch.isdigit()
        )

        if num:
            return float(num), None

        return None

    if "-" in cleaned:
        left, _, right = cleaned.partition("-")

        left_n = "".join(
            ch for ch in left
            if ch.isdigit()
        )

        right_n = "".join(
            ch for ch in right
            if ch.isdigit()
        )

        if left_n and right_n:
            return (
                float(left_n),
                float(right_n),
            )

    return None


