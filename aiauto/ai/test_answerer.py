def _looks_like_personal_life_question(
    question: str,
) -> bool:
    low = str(question or "").lower()

    if _text_has_any(
        low,
        _PERSONAL_LIFE_HISTORY_MARKERS,
    ):
        return True

    # ИСПРАВЛЕНИЕ: достижения/дипломы/уровень английского — тоже
    # открытые вопросы про биографию, для которых PROFILE_FACTS
    # может ничего не содержать. Раньше это решал сам Qwen внутри
    # промпта и почти всегда уходил в needs_manual_input.
    if _text_has_any(
        low,
        _UNVERIFIABLE_OPEN_FACT_MARKERS,
    ):
        return True

    # ДОБАВЛЕНО (5): точные фразы выше не покрывают все
    # формулировки одного и того же вопроса (например "Какая
    # механика в игре, в которую играли, понравилась?" — слова
